// Recettes « longévité » : aliments bruts, méditerranéen/japonais, riches en protéines,
// fibres, polyphénols, oméga-3, aliments fermentés. Les quantités sont des bases
// que le planificateur ajuste automatiquement à tes macros.

export type Role = 'protein' | 'carb' | 'fat' | 'veg' | 'fixed';
export type Slot = 'breakfast' | 'main' | 'snack';

export interface Ingredient {
  food: string;
  g: number;
  role: Role;
  /** Ingrédient indispensable : pas de substitution possible */
  strict?: boolean;
}

export interface Recipe {
  id: string;
  /** `{foodId}` est remplacé par le nom court de l'aliment (ou de son substitut) */
  name: string;
  slots: Slot[];
  minutes: number;
  ingredients: Ingredient[];
  steps: string[];
  /** Limite hebdomadaire (viande rouge, thon…) */
  maxPerWeek?: number;
  tip?: string;
}

const i = (food: string, g: number, role: Role, strict?: boolean): Ingredient => (strict ? { food, g, role, strict } : { food, g, role });

